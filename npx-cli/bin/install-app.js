const fs = require("fs");
const os = require("os");
const path = require("path");
const { execFileSync } = require("child_process");

/**
 * Installs Kablan into ~/Applications as a real macOS app.
 *
 * The point is a double-clickable icon that starts Kablan in the background — no Terminal
 * window, no command to remember. It also happens to sidestep Gatekeeper: the bundle is
 * assembled here, on this machine, from a binary this process downloaded, so nothing carries the
 * quarantine flag that produces "unidentified developer". A downloaded .app would need
 * notarisation and a paid Apple account; one built locally needs neither.
 */

const APP_NAME = "Kablan";
const BUNDLE_ID = "dev.kablan.app";

function appDir() {
  // ~/Applications rather than /Applications: it needs no password, and Spotlight and Launchpad
  // both index it.
  return path.join(os.homedir(), "Applications", `${APP_NAME}.app`);
}

/**
 * A GUI-launched process inherits a minimal PATH — roughly /usr/bin:/bin — so the coding agents,
 * node and pnpm are all missing and every task fails at its first command. The launcher asks the
 * login shell what PATH really is, the same thing a terminal would have.
 */
function launcherScript() {
  const bin = APP_NAME.toLowerCase();
  return `#!/bin/bash
# Generated by \`npx kablan --install\`. Re-run that to update this launcher.
#
# This script starts Kablan and then exits. It must exit: a .app whose executable never returns
# is one macOS is still waiting to see register with the window server, so the Dock icon bounces
# and the app is eventually reported as not responding — which is what happens if you exec the
# server here instead of detaching it.
set -u

HERE="$(cd "$(dirname "$0")" && pwd)"

# A GUI launch inherits almost no PATH, so node, pnpm and the coding agents are all missing.
# Take the login shell's PATH, which is what a terminal would have.
SHELL_BIN="\${SHELL:-/bin/zsh}"
RESOLVED="$("$SHELL_BIN" -ilc 'printf %s "$PATH"' 2>/dev/null || true)"
if [ -n "$RESOLVED" ]; then
  export PATH="$RESOLVED"
fi
for dir in /opt/homebrew/bin /usr/local/bin /usr/bin /bin; do
  case ":$PATH:" in *":$dir:"*) ;; *) PATH="$dir:$PATH" ;; esac
done
export PATH

LOG_DIR="$HOME/Library/Logs/${APP_NAME}"
mkdir -p "$LOG_DIR"
LOG="$LOG_DIR/${bin}.log"

# Where the server publishes the port it bound, so a second launch can find the first.
TMP="\${TMPDIR:-/tmp}"
PORT_FILE="\${TMP%/}/${bin}/${bin}.port"

# Already running? Bring it up rather than starting a second copy on another port.
PORT="$(cat "$PORT_FILE" 2>/dev/null || true)"
if [ -n "$PORT" ] && curl -fsS -o /dev/null --max-time 2 "http://127.0.0.1:$PORT/api/info"; then
  open "http://127.0.0.1:$PORT"
  exit 0
fi

# Prefer the published wrapper so opening the icon runs the newest release rather than whatever
# was current on the day this was installed. The copy inside the bundle is the fallback for a
# machine without node, or one that cannot reach the registry.
{
  echo "--- $(date '+%Y-%m-%d %H:%M:%S') launching"
  if command -v npx >/dev/null 2>&1; then
    echo "using npx kablan@latest"
  else
    echo "npx not found; using the bundled ${bin}-server"
  fi
} >>"$LOG" 2>&1

if command -v npx >/dev/null 2>&1; then
  nohup npx -y ${bin}@latest >>"$LOG" 2>&1 &
else
  nohup "$HERE/${bin}-server" >>"$LOG" 2>&1 &
fi

# The server opens the browser itself once it is listening, so there is nothing left to wait for.
exit 0
`;
}

function infoPlist(version) {
  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key><string>${APP_NAME}</string>
  <key>CFBundleDisplayName</key><string>${APP_NAME}</string>
  <key>CFBundleIdentifier</key><string>${BUNDLE_ID}</string>
  <key>CFBundleVersion</key><string>${version}</string>
  <key>CFBundleShortVersionString</key><string>${version}</string>
  <key>CFBundleExecutable</key><string>${APP_NAME}</string>
  <key>CFBundleIconFile</key><string>${APP_NAME}</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleInfoDictionaryVersion</key><string>6.0</string>
  <key>NSHighResolutionCapable</key><true/>
  <key>LSMinimumSystemVersion</key><string>11.0</string>
</dict>
</plist>
`;
}


/**
 * Stop a Kablan that is already running, and say whether one was.
 *
 * Replacing the bundle under a live process does nothing to that process: it keeps serving, the
 * launcher finds its port file and simply opens a browser at it, and the update looks like it
 * failed — the app still reports the version it was started with. So the install stops it first.
 *
 * The port file is the only handle we have on it. Whoever is listening on that port has to look
 * like Kablan before it is signalled, because a stale port file plus a recycled port would
 * otherwise point at some unrelated process. SIGTERM first so the server can close its database
 * cleanly; SIGKILL only if it is still there after a grace period.
 *
 * @returns the pid stopped, or null when nothing was running
 */
function stopRunningApp() {
  const bin = APP_NAME.toLowerCase();
  const tmp = process.env.TMPDIR || "/tmp";
  const portFile = path.join(tmp, bin, `${bin}.port`);

  let port;
  try {
    port = fs.readFileSync(portFile, "utf8").trim();
  } catch {
    return null;
  }
  if (!/^\d+$/.test(port)) return null;

  let pids;
  try {
    pids = execFileSync("/usr/sbin/lsof", ["-ti", `tcp:${port}`, "-sTCP:LISTEN"], {
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
    })
      .split("\n")
      .map((line) => line.trim())
      .filter(Boolean);
  } catch {
    // Nothing listening: the port file outlived the process it described.
    return null;
  }

  for (const pid of pids) {
    let command = "";
    try {
      command = execFileSync("/bin/ps", ["-o", "command=", "-p", pid], {
        encoding: "utf8",
        stdio: ["ignore", "pipe", "ignore"],
      }).trim();
    } catch {
      continue;
    }
    // Ours: either a cached release binary or the one inside the bundle.
    if (!command.includes(`.${bin}/bin/`) && !command.includes(`${bin}-server`)) continue;

    try {
      process.kill(Number(pid), "SIGTERM");
    } catch {
      continue;
    }

    // Give it a moment to close its database before resorting to SIGKILL.
    const deadline = Date.now() + 5000;
    while (Date.now() < deadline) {
      try {
        process.kill(Number(pid), 0);
      } catch {
        return pid; // gone
      }
      execFileSync("/bin/sleep", ["0.2"]);
    }
    try {
      process.kill(Number(pid), "SIGKILL");
    } catch {
      // Raced us to exit.
    }
    return pid;
  }

  return null;
}

/**
 * @param binPath  the extracted server binary to install
 * @param version  the wrapper's version, shown in Finder's Get Info
 * @returns {{ app: string, stoppedPid: string | null }}
 */
function installMacApp(binPath, version) {
  if (process.platform !== "darwin") {
    throw new Error(
      `--install builds a macOS app bundle and this is ${process.platform}.\n` +
        `On Linux and Windows, run \`npx kablan\` directly.`
    );
  }

  // Before anything is replaced: a running copy would survive the swap and keep serving the
  // version it started with.
  const stoppedPid = stopRunningApp();

  const app = appDir();
  const macos = path.join(app, "Contents", "MacOS");
  const resources = path.join(app, "Contents", "Resources");

  // Replace wholesale rather than merging, so an older layout cannot leave stale files behind.
  fs.rmSync(app, { recursive: true, force: true });
  fs.mkdirSync(macos, { recursive: true });
  fs.mkdirSync(resources, { recursive: true });

  fs.writeFileSync(path.join(app, "Contents", "Info.plist"), infoPlist(version));

  const serverName = `${APP_NAME.toLowerCase()}-server`;
  fs.copyFileSync(binPath, path.join(macos, serverName));
  fs.chmodSync(path.join(macos, serverName), 0o755);

  const launcher = path.join(macos, APP_NAME);
  fs.writeFileSync(launcher, launcherScript());
  fs.chmodSync(launcher, 0o755);

  const icon = path.join(__dirname, "..", "assets", `${APP_NAME}.icns`);
  if (fs.existsSync(icon)) {
    fs.copyFileSync(icon, path.join(resources, `${APP_NAME}.icns`));
  }

  // Finder caches icons per bundle; without this the app can show a blank page icon until
  // something else invalidates it.
  try {
    execFileSync("/usr/bin/touch", [app]);
    execFileSync(
      "/System/Library/Frameworks/CoreServices.framework/Frameworks/LaunchServices.framework/Support/lsregister",
      ["-f", app],
      { stdio: "ignore" }
    );
  } catch {
    // Cosmetic only — the app works either way.
  }

  return { app, stoppedPid };
}

function uninstallMacApp() {
  // Removing the bundle from under a running server leaves it running with no way back to it.
  const stoppedPid = stopRunningApp();
  const app = appDir();
  if (!fs.existsSync(app)) return { app: null, stoppedPid };
  fs.rmSync(app, { recursive: true, force: true });
  return { app, stoppedPid };
}

module.exports = { installMacApp, uninstallMacApp, stopRunningApp, appDir, APP_NAME };
