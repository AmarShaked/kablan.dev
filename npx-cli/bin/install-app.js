const fs = require("fs");
const os = require("os");
const path = require("path");
const { execFileSync } = require("child_process");

/**
 * Installs Kablan into ~/Applications as a real macOS app.
 *
 * The point is a double-clickable icon that starts Kablan in the background — no Terminal
 * window, no command to remember. It also happens to sidestep Gatekeeper: the bundle is
 * assembled here, on this machine, from a binary this process downloaded, so nothing carries the
 * quarantine flag that produces "unidentified developer". A downloaded .app would need
 * notarisation and a paid Apple account; one built locally needs neither.
 */

const APP_NAME = "Kablan";
const BUNDLE_ID = "dev.kablan.app";

function appDir() {
  // ~/Applications rather than /Applications: it needs no password, and Spotlight and Launchpad
  // both index it.
  return path.join(os.homedir(), "Applications", `${APP_NAME}.app`);
}

/**
 * A GUI-launched process inherits a minimal PATH — roughly /usr/bin:/bin — so the coding agents,
 * node and pnpm are all missing and every task fails at its first command. The launcher asks the
 * login shell what PATH really is, the same thing a terminal would have.
 */
function launcherScript() {
  const bin = APP_NAME.toLowerCase();
  return `#!/bin/bash
# Generated by \`npx kablan --install\`. Re-run that to update this launcher.
#
# This script starts Kablan and then exits. It must exit: a .app whose executable never returns
# is one macOS is still waiting to see register with the window server, so the Dock icon bounces
# and the app is eventually reported as not responding — which is what happens if you exec the
# server here instead of detaching it.
set -u

HERE="$(cd "$(dirname "$0")" && pwd)"

# A GUI launch inherits almost no PATH, so node, pnpm and the coding agents are all missing.
# Take the login shell's PATH, which is what a terminal would have.
SHELL_BIN="\${SHELL:-/bin/zsh}"
RESOLVED="$("$SHELL_BIN" -ilc 'printf %s "$PATH"' 2>/dev/null || true)"
if [ -n "$RESOLVED" ]; then
  export PATH="$RESOLVED"
fi
for dir in /opt/homebrew/bin /usr/local/bin /usr/bin /bin; do
  case ":$PATH:" in *":$dir:"*) ;; *) PATH="$dir:$PATH" ;; esac
done
export PATH

LOG_DIR="$HOME/Library/Logs/${APP_NAME}"
mkdir -p "$LOG_DIR"
LOG="$LOG_DIR/${bin}.log"

# Where the server publishes the port it bound, so a second launch can find the first.
TMP="\${TMPDIR:-/tmp}"
PORT_FILE="\${TMP%/}/${bin}/${bin}.port"

# Already running? Bring it up rather than starting a second copy on another port.
PORT="$(cat "$PORT_FILE" 2>/dev/null || true)"
if [ -n "$PORT" ] && curl -fsS -o /dev/null --max-time 2 "http://127.0.0.1:$PORT/api/info"; then
  open "http://127.0.0.1:$PORT"
  exit 0
fi

# Prefer the published wrapper so opening the icon runs the newest release rather than whatever
# was current on the day this was installed. The copy inside the bundle is the fallback for a
# machine without node, or one that cannot reach the registry.
{
  echo "--- $(date '+%Y-%m-%d %H:%M:%S') launching"
  if command -v npx >/dev/null 2>&1; then
    echo "using npx kablan@latest"
  else
    echo "npx not found; using the bundled ${bin}-server"
  fi
} >>"$LOG" 2>&1

if command -v npx >/dev/null 2>&1; then
  nohup npx -y ${bin}@latest >>"$LOG" 2>&1 &
else
  nohup "$HERE/${bin}-server" >>"$LOG" 2>&1 &
fi

# The server opens the browser itself once it is listening, so there is nothing left to wait for.
exit 0
`;
}

function infoPlist(version) {
  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key><string>${APP_NAME}</string>
  <key>CFBundleDisplayName</key><string>${APP_NAME}</string>
  <key>CFBundleIdentifier</key><string>${BUNDLE_ID}</string>
  <key>CFBundleVersion</key><string>${version}</string>
  <key>CFBundleShortVersionString</key><string>${version}</string>
  <key>CFBundleExecutable</key><string>${APP_NAME}</string>
  <key>CFBundleIconFile</key><string>${APP_NAME}</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleInfoDictionaryVersion</key><string>6.0</string>
  <key>NSHighResolutionCapable</key><true/>
  <key>LSMinimumSystemVersion</key><string>11.0</string>
</dict>
</plist>
`;
}


/**
 * Stops every Kablan server this installer manages, and says what it did.
 *
 * The version is baked into the running process, so a copy that survives an update keeps serving
 * the old build — the update looks like it silently failed. This used to read
 * `$TMPDIR/kablan/kablan.port` and stop whoever held that port, which turned out to be one slot
 * shared by every instance: a second server (a release build run from a checkout, say)
 * overwrites it, and the installer then goes looking at the wrong port and stops nothing while
 * the real app keeps running. That is a silent wrong answer, so the port file is no longer the
 * handle.
 *
 * Instead every process is examined and the ones that are ours are stopped — all of them, not
 * the first. "Ours" means two things, and both are required:
 *
 *   - the executable lives in a directory *this* install owns: the version cache under
 *     $HOME/.kablan/bin, or an app bundle in $HOME/Applications (or /Applications, for a copy
 *     dragged there);
 *   - the process runs as the uid that invoked us.
 *
 * The scan stays machine-wide — reading the process table rather than a port file is what fixed
 * the bug above — but a machine-wide scan with no ownership test signals servers that are none
 * of our business: another account's, or the same account running under a different HOME. An
 * install for one HOME must not stop a server installed under another, and it used to.
 *
 * A server someone compiled themselves is left alone for the same reason it always was: it is
 * not what an update replaces.
 *
 * SIGTERM first, so the server closes its database cleanly; SIGKILL only for one that outstays
 * the grace period.
 *
 * @param {object} [deps] seams for the tests: every call to the outside world goes through one
 * @returns {{stopped: Array<{pid: number, kind: string, version: string|null, signal: string}>,
 *            skipped: Array<{pid: number, reason: string}>}}
 */
function stopRunningApps(deps = {}) {
  const {
    listProcesses = defaultListProcesses,
    homeDir = os.homedir(),
    // Windows has no getuid. There the path test stands alone, which gives up only the
    // multi-user case — and `--install` does not run on Windows at all.
    uid = typeof process.getuid === "function" ? process.getuid() : null,
    kill = (pid, signal) => process.kill(pid, signal),
    alive = (pid) => {
      try {
        process.kill(pid, 0);
        return true;
      } catch {
        return false;
      }
    },
    sleep = () => execFileSync("/bin/sleep", ["0.2"]),
    now = () => Date.now(),
    graceMs = 5000,
    selfPid = process.pid,
    parentPid = process.ppid,
    log = () => {},
  } = deps;

  const stopped = [];
  const skipped = [];

  for (const { pid, command, uid: processUid } of listProcesses()) {
    const kind = classify(command, homeDir);
    if (!kind) continue;

    // Signalling ourselves or the npx wrapper that spawned us would end the install midway.
    if (pid === selfPid || pid === parentPid) {
      skipped.push({ pid, reason: "self" });
      continue;
    }

    // One of our paths, but under another account. `ps` reports a uid for every process it
    // lists, so a missing one means the column was unavailable — not that the process is
    // unowned — and then the path test above is the whole answer.
    if (uid !== null && processUid !== null && processUid !== undefined && processUid !== uid) {
      skipped.push({ pid, reason: "another user" });
      continue;
    }

    const version = versionFromPath(command);
    log(`Stopping ${kind}${version ? ` ${version}` : ""} (pid ${pid})`);

    try {
      kill(pid, "SIGTERM");
    } catch {
      // Gone between listing and signalling, or not ours to signal.
      skipped.push({ pid, reason: "could not signal" });
      continue;
    }

    let signal = "SIGTERM";
    const deadline = now() + graceMs;
    while (alive(pid)) {
      if (now() >= deadline) {
        try {
          kill(pid, "SIGKILL");
          signal = "SIGKILL";
          log(`  pid ${pid} ignored SIGTERM for ${graceMs / 1000}s; sent SIGKILL`);
        } catch {
          // Raced us to exit.
        }
        break;
      }
      sleep();
    }

    stopped.push({ pid, kind, version, signal });
  }

  return { stopped, skipped };
}

/**
 * The directories an install under `homeDir` owns, and what a binary found in each one is.
 *
 * These are prefixes, matched against the executable path — not substrings of it. A substring
 * match is what let an install under one HOME claim a server under another: every cache path
 * ends in `/.kablan/bin/`, whoever's home it sits in.
 *
 * /Applications is included because a user can drag the bundle there, and an update that left
 * that copy running would be the silent-old-version failure all of this exists to prevent. The
 * uid test in stopRunningApps is what keeps another account's copy out.
 */
function ownedRoots(homeDir) {
  const bin = APP_NAME.toLowerCase();
  const bundle = path.join(`${APP_NAME}.app`, "Contents", "MacOS");
  return [
    { prefix: path.join(homeDir, `.${bin}`, "bin") + path.sep, kind: "cache" },
    { prefix: path.join(homeDir, "Applications", bundle) + path.sep, kind: "bundle" },
    { prefix: path.sep + path.join("Applications", bundle) + path.sep, kind: "bundle" },
  ];
}

/**
 * Is this command line one of ours, and which kind? Anything else returns null and is left
 * running — including a server built from a checkout, which no update of ours replaces, and one
 * cached under a different HOME, which this install does not manage.
 *
 * Only the executable is examined, never the arguments. `ps` prints the whole command line, so a
 * shell that launched a server, a `tail` on its log, or an editor with the path open all carry
 * our directory in their arguments; matching anywhere in the line would signal them.
 */
function classify(command, homeDir = os.homedir()) {
  const bin = APP_NAME.toLowerCase();
  const executable = executableOf(command);

  for (const { prefix, kind } of ownedRoots(homeDir)) {
    if (!executable.startsWith(prefix)) continue;
    if (kind === "bundle") return "installed app";
    return executable.endsWith(`${bin}-mcp`) ? "MCP server" : "server";
  }
  return null;
}

/**
 * The executable out of a `ps` command line — everything up to the first space.
 *
 * A path containing a space would be cut short and so not recognised as ours; the alternative,
 * matching the whole line, mistakes every process that merely mentions the path for a server,
 * and signalling the wrong process is the worse failure.
 */
function executableOf(command) {
  const space = command.indexOf(" ");
  return space === -1 ? command : command.slice(0, space);
}

/**
 * Which cached versions have something running out of them right now.
 *
 * The cache sweeper asks this before it deletes anything: another Kablan may be serving an older
 * version this second, and a sweep that removed its binary would be a worse bug than the disk it
 * reclaimed. Same process table and the same ownership test as stopRunningApps — the difference
 * is that this one only looks, and that an installed app bundle is not a cache directory and so
 * contributes no version here.
 *
 * Returns `null`, not an empty set, when the process table cannot be read: `defaultListProcesses`
 * answers `[]` both when `ps` is missing — Windows, where there is no `/bin/ps` — and when it
 * failed, and neither means "nothing of ours is running". A real process table always contains at
 * least this process, so an empty one is a failure to read, and the sweeper treats it as a
 * refusal rather than as permission.
 *
 * @param {object} [deps] seams for the tests
 * @returns {Set<string>|null} version directory names, e.g. "v0.11.6"
 */
function runningCacheVersions(deps = {}) {
  const { listProcesses = defaultListProcesses, homeDir = os.homedir() } = deps;

  let processes;
  try {
    processes = listProcesses();
  } catch {
    return null;
  }
  if (!Array.isArray(processes) || processes.length === 0) return null;

  const versions = new Set();
  for (const { command } of processes) {
    if (!classify(command, homeDir)) continue;
    const version = versionFromPath(command);
    if (version) versions.add(version);
  }
  return versions;
}

/** ~/.kablan/bin/v0.9.1/macos-arm64/kablan -> "v0.9.1". Best effort; null when the path differs. */
function versionFromPath(command) {
  const match = command.match(/\/\.?[a-z]+\/bin\/(v[\d.]+)\//);
  return match ? match[1] : null;
}

/**
 * Every process on the machine, as {pid, uid, command}.
 *
 * The uid is what tells one account's server from another's. If `ps` will not give it — no
 * platform we ship to refuses, but the fallback costs one line — the uid comes back undefined
 * and the caller falls back to the path test alone rather than listing nothing.
 */
function defaultListProcesses() {
  const run = (format) =>
    execFileSync("/bin/ps", ["-axo", format], {
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
      maxBuffer: 8 * 1024 * 1024,
    });

  let out = "";
  let hasUid = true;
  try {
    out = run("pid=,uid=,command=");
  } catch {
    try {
      out = run("pid=,command=");
      hasUid = false;
    } catch {
      return [];
    }
  }

  const pattern = hasUid ? /^(\d+)\s+(\d+)\s+(.*)$/ : /^(\d+)\s+(.*)$/;

  return out
    .split("\n")
    .map((line) => line.trim())
    .filter(Boolean)
    .map((line) => {
      const match = line.match(pattern);
      if (!match) return null;
      const pid = Number(match[1]);
      if (!Number.isInteger(pid)) return null;
      return hasUid
        ? { pid, uid: Number(match[2]), command: match[3].trim() }
        : { pid, uid: undefined, command: match[2].trim() };
    })
    .filter(Boolean);
}

/**
 * @param binPath  the extracted server binary to install
 * @param version  the wrapper's version, shown in Finder's Get Info
 * @param log      where progress goes; the caller tees this to the console and a file
 * @returns {{ app: string, stopped: Array<object> }}
 */
function installMacApp(binPath, version, log = () => {}) {
  if (process.platform !== "darwin") {
    throw new Error(
      `--install builds a macOS app bundle and this is ${process.platform}.\n` +
        `On Linux and Windows, run \`npx kablan\` directly.`
    );
  }

  // Before anything is replaced: a running copy would survive the swap and keep serving the
  // version it started with.
  const { stopped } = stopRunningApps({ log });
  if (stopped.length === 0) log("No running Kablan found; nothing to stop");

  const app = appDir();
  const macos = path.join(app, "Contents", "MacOS");
  const resources = path.join(app, "Contents", "Resources");

  // Replace wholesale rather than merging, so an older layout cannot leave stale files behind.
  fs.rmSync(app, { recursive: true, force: true });
  fs.mkdirSync(macos, { recursive: true });
  fs.mkdirSync(resources, { recursive: true });

  fs.writeFileSync(path.join(app, "Contents", "Info.plist"), infoPlist(version));

  const serverName = `${APP_NAME.toLowerCase()}-server`;
  fs.copyFileSync(binPath, path.join(macos, serverName));
  fs.chmodSync(path.join(macos, serverName), 0o755);

  const launcher = path.join(macos, APP_NAME);
  fs.writeFileSync(launcher, launcherScript());
  fs.chmodSync(launcher, 0o755);

  const icon = path.join(__dirname, "..", "assets", `${APP_NAME}.icns`);
  if (fs.existsSync(icon)) {
    fs.copyFileSync(icon, path.join(resources, `${APP_NAME}.icns`));
  }

  // Finder caches icons per bundle; without this the app can show a blank page icon until
  // something else invalidates it.
  try {
    execFileSync("/usr/bin/touch", [app]);
    execFileSync(
      "/System/Library/Frameworks/CoreServices.framework/Frameworks/LaunchServices.framework/Support/lsregister",
      ["-f", app],
      { stdio: "ignore" }
    );
  } catch {
    // Cosmetic only — the app works either way.
  }

  return { app, stopped };
}

function uninstallMacApp(log = () => {}) {
  // Removing the bundle from under a running server leaves it running with no way back to it.
  const { stopped } = stopRunningApps({ log });
  const app = appDir();
  if (!fs.existsSync(app)) return { app: null, stopped };
  fs.rmSync(app, { recursive: true, force: true });
  return { app, stopped };
}

/**
 * Where the server keeps your boards, tasks and settings.
 *
 * This mirrors `ProjectDirs::from("dev", "kablan", "Kablan").data_dir()` in
 * crates/utils/src/assets.rs. If that ever moves, this is wrong, and what it is wrong about is
 * a path printed next to the words "deleting this deletes your Kablan history" — so it is worth
 * the duplication being written down rather than guessed at.
 */
function dataDir(homeDir = os.homedir(), platform = process.platform, env = process.env) {
  if (platform === "darwin") {
    return path.join(homeDir, "Library", "Application Support", "dev.kablan.Kablan");
  }
  if (platform === "win32") {
    const appData = env.APPDATA || path.join(homeDir, "AppData", "Roaming");
    return path.join(appData, "kablan", "Kablan", "data");
  }
  return path.join(env.XDG_DATA_HOME || path.join(homeDir, ".local", "share"), "kablan");
}

/** Bytes under `dir`, or null if it is not there. Symlinks are not followed and not counted. */
function dirSize(dir) {
  let entries;
  try {
    entries = fs.readdirSync(dir, { withFileTypes: true });
  } catch {
    return null;
  }

  let total = 0;
  for (const entry of entries) {
    const child = path.join(dir, entry.name);
    try {
      if (entry.isDirectory()) total += dirSize(child) || 0;
      else if (entry.isFile()) total += fs.statSync(child).size;
    } catch {
      // Raced us, or not readable. A size that is slightly low beats no answer at all.
    }
  }
  return total;
}

function formatBytes(bytes) {
  const units = ["B", "KB", "MB", "GB", "TB"];
  let value = bytes;
  let unit = 0;
  while (value >= 1024 && unit < units.length - 1) {
    value /= 1024;
    unit += 1;
  }
  const rounded = unit === 0 || value >= 10 ? Math.round(value) : value.toFixed(1);
  return `${rounded} ${units[unit]}`;
}

/** `~/.kablan/bin` to read, `"$HOME/.kablan/bin"` to paste into a shell. */
function tildePath(target, homeDir) {
  return target.startsWith(homeDir + path.sep) ? `~${target.slice(homeDir.length)}` : target;
}

function shellPath(target, homeDir) {
  const expanded = target.startsWith(homeDir + path.sep)
    ? `$HOME${target.slice(homeDir.length)}`
    : target;
  // Double quotes rather than single: the paths that need quoting are the ones with a space in
  // them, and those are also the ones written relative to $HOME.
  return `"${expanded.replace(/"/g, '\\"')}"`;
}

/**
 * What `--uninstall` leaves behind, with sizes, in order of how much space it is.
 *
 * Removing the app used to be followed by one line naming `~/.kablan/bin` and nothing else,
 * which is the wrong half: the database under Application Support is usually the larger of the
 * two by far, and someone uninstalling to reclaim disk was being sent to the smaller one and
 * told that was all there was. Deleting the data directory also deletes every board and task,
 * so it needs saying out loud rather than being left out.
 *
 * @returns {string[]} lines to print, or [] when nothing is left on disk
 */
function describeLeftovers(deps = {}) {
  const {
    homeDir = os.homedir(),
    platform = process.platform,
    env = process.env,
    sizeOf = dirSize,
  } = deps;

  const bin = APP_NAME.toLowerCase();
  const found = [
    {
      path: path.join(homeDir, `.${bin}`, "bin"),
      note: "Cached binaries, one directory per version you have run. Safe to delete.",
      keepsData: false,
    },
    {
      path: dataDir(homeDir, platform, env),
      note:
        "Your projects, tasks, settings and database.\n" +
        "Deleting this deletes your Kablan history.",
      keepsData: true,
    },
    ...(platform === "darwin"
      ? [
          {
            path: path.join(homeDir, "Library", "Logs", APP_NAME),
            note: "Logs. Safe to delete.",
            keepsData: false,
          },
        ]
      : []),
  ]
    .map((entry) => ({ ...entry, size: sizeOf(entry.path) }))
    .filter((entry) => entry.size !== null);

  if (found.length === 0) return [];

  const lines = ["", `${APP_NAME} still has this on disk:`, ""];
  for (const entry of found) {
    lines.push(`  ${formatBytes(entry.size).padStart(7)}  ${tildePath(entry.path, homeDir)}`);
    for (const noteLine of entry.note.split("\n")) {
      lines.push(`           ${noteLine}`);
    }
  }

  // `rm -rf` is not a thing on Windows, and the paths above are enough to act on there.
  if (platform === "win32") return lines;

  const disposable = found.filter((e) => !e.keepsData);
  const data = found.filter((e) => e.keepsData);

  if (disposable.length > 0) {
    lines.push("", "Reclaim the space, keep your boards and tasks:");
    lines.push(`  rm -rf ${disposable.map((e) => shellPath(e.path, homeDir)).join(" ")}`);
  }
  if (data.length > 0) {
    lines.push("", "Remove everything, boards and tasks included:");
    lines.push(`  rm -rf ${found.map((e) => shellPath(e.path, homeDir)).join(" ")}`);
  }

  return lines;
}

